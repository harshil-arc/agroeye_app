/**
 * Helper to find city by ID or fuzzy text search
 */
export function searchCityMonsoon(query: string): CityMonsoonData[] {
  if (!query || query.trim() === '') return CITIES_MONSOON_DATA.slice(0, 10);
  const q = query.toLowerCase().trim();
  return CITIES_MONSOON_DATA.filter(
    (c) =>
      c.name.toLowerCase().includes(q) ||
      c.nameHi.includes(q) ||
      c.stateName.toLowerCase().includes(q) ||
      c.stateNameHi.includes(q) ||
      c.id.toLowerCase().includes(q)
  );
}

export function getCityById(id: string): CityMonsoonData {
  return (
    CITIES_MONSOON_DATA.find((c) => c.id.toLowerCase() === id.toLowerCase()) ||
    CITIES_MONSOON_DATA[0]
  );
}
